"""bb_constants.py -- the prime-independent constants of the rigorous prover bb.c, in exact rational arithmetic.

Writes bb_constants.h: pi, 2 pi and pi/2 as pairs of adjacent doubles enclosing them (pi from Machin's formula,
pi = 16 atan(1/5) - 4 atan(1/239), each arctangent between two consecutive partial sums of its alternating series),
the Taylor coefficients +-1/n! of cos and sin, and the Lagrange remainders RMAX^18/18! and RMAX^19/19! for the exact
value of the double RMAX = 0.8.  Every double is chosen by exact comparison with a rational number.  The constants
that depend on the prime (2 pi k/p, pi/p) are computed by bb.c itself in interval arithmetic.

Usage: python bb_constants.py [--check]   (--check: verify bb_constants.h is exactly what it would write)
"""
import math
import os
import struct
import sys
from fractions import Fraction as Q

HERE = os.path.dirname(os.path.abspath(__file__))
NT, RMAX = 8, 0.8


def atan_inv(x, terms):
    s, prev = Q(0), Q(0)
    for n in range(terms + 1):
        prev = s
        s = s + Q((-1) ** n, (2 * n + 1) * x ** (2 * n + 1))
    return min(prev, s), max(prev, s)


a_lo, a_hi = atan_inv(5, 70)
b_lo, b_hi = atan_inv(239, 25)
PI = (16 * a_lo - 4 * b_hi, 16 * a_hi - 4 * b_lo)


def lo_double(q):
    d = float(q)
    while Q(d) > q:
        d = math.nextafter(d, -math.inf)
    while Q(math.nextafter(d, math.inf)) <= q:
        d = math.nextafter(d, math.inf)
    return d


def hi_double(q):
    d = float(q)
    while Q(d) < q:
        d = math.nextafter(d, math.inf)
    while Q(math.nextafter(d, -math.inf)) >= q:
        d = math.nextafter(d, -math.inf)
    return d


def bits(d):
    return struct.unpack("<Q", struct.pack("<d", d))[0]


lines = ["/* bb_constants.h -- generated by bb_constants.py; each constant is a pair of doubles enclosing a real number */",
         "#include <stdint.h>"]


def emit(name, lo, hi):
    lines.append(f"static const uint64_t {name}_LO_B = 0x{bits(lo):016x}ULL; /* {lo!r} */")
    lines.append(f"static const uint64_t {name}_HI_B = 0x{bits(hi):016x}ULL; /* {hi!r} */")


def emit_arr(name, qs):
    lines.append(f"static const uint64_t {name}_LO_B[{len(qs)}] = {{" + ", ".join(f"0x{bits(lo_double(q)):016x}ULL" for q in qs) + "};")
    lines.append(f"static const uint64_t {name}_HI_B[{len(qs)}] = {{" + ", ".join(f"0x{bits(hi_double(q)):016x}ULL" for q in qs) + "};")


emit("PI", lo_double(PI[0]), hi_double(PI[1]))
emit("TWO_PI", lo_double(2 * PI[0]), hi_double(2 * PI[1]))
emit("PIO2", lo_double(PI[0] / 2), hi_double(PI[1] / 2))
emit_arr("COSC", [Q((-1) ** j, math.factorial(2 * j)) for j in range(NT + 1)])
emit_arr("SINC", [Q((-1) ** j, math.factorial(2 * j + 1)) for j in range(NT + 1)])
remc = Q(RMAX) ** (2 * NT + 2) / math.factorial(2 * NT + 2)
rems = Q(RMAX) ** (2 * NT + 3) / math.factorial(2 * NT + 3)
emit("REMC", lo_double(remc), hi_double(remc))
emit("REMS", lo_double(rems), hi_double(rems))
lines.append(f"#define NT {NT}")
lines.append(f"static const uint64_t RMAX_B = 0x{bits(RMAX):016x}ULL; /* {RMAX!r}: the remainders above assume exactly this double */")
text = "\n".join(lines) + "\n"
path = os.path.join(HERE, "bb_constants.h")
if "--check" in sys.argv:
    same = os.path.exists(path) and open(path, encoding="utf-8").read() == text
    print(f"[{'PASS' if same else 'FAIL'}] bb_constants.h is exactly what bb_constants.py generates "
          f"(pi enclosed to {float(PI[1] - PI[0]):.1e})")
    sys.exit(0 if same else 1)
open(path, "w", encoding="utf-8").write(text)
print(f"wrote bb_constants.h (pi enclosed to {float(PI[1] - PI[0]):.1e})")
