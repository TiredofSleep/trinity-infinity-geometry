"""verify_cm_pieces.py -- checks CM_PIECES.md, Theorem 9: the Airy pieces at 7, 11 and 15 are induced from unramified
Hecke characters, so they are CM newforms of weight 3 and levels 35, 1155 and 3003.

    "Livne proof first, then the p^2-root phases"  -- the author, 17 November 2026

The argument (Livne, Israel J. Math. 92, 1995).  rho = V_n twisted to weight 0 is two-dimensional and orthogonal (the
cup product on the even-dimensional middle cohomology), with distinct Hodge-Tate weights.  Theorem 8 gives det rho =
(D|.), D = -35, -1155, -3003, a nontrivial quadratic character.  So rho is irreducible, rho(G_K) lies in SO(2), which is
abelian, for K = Q(sqrt D), and rho = Ind_K psi for an algebraic Hecke character psi of infinity type z^2.  Corollary 2
gives the conductor: |D| itself (for n = 15 after twisting by (5|.)), so psi is unramified.  K's class group has
exponent 2 and is generated by the ramified primes, so psi is fixed by psi(p_l) = s_l l on the ramified primes p_l, with
prod s_l = -1 because psi((sqrt D)) = D.  That leaves 2, 8, 8 candidates, and the measured traces must pick one.

For a split prime p, p_bar in the class of the product a_S of the chosen ramified primes in S, there is gamma with
(gamma) = p a_S, gamma = (u + v sqrt D)/2, u^2 + |D| v^2 = 4 p m (m = prod S).  Then
    a_p(theta_psi) = psi(p) + psi(p_bar) = (gamma^2 + gamma_bar^2) / psi(a_S) = (2 p m + D v^2) / (m prod_(l in S) s_l).

  M0. The class groups: the 2^r products a_S are non-principal and distinct, h(D) = 2^r by reduced forms, and every split
      prime below 3000 lies in exactly one class a_S.
  M1. The inputs from Theorem 8 and Corollary 2: det and conductor (recomputed from the nodes).
  M2. Of the 2^r candidates, exactly one has the measured traces at every good prime from 11 to 401.
  M3. Its signs at the ramified primes agree with the edge counts (and with the functional equation's a_3 = +3).
  M4. At 7 it is LMFDB's 35.3.c.b, coefficient by coefficient, a_2 and a_3 included (Chenevert's theorem, by Livne's
      route).

numpy + sympy + edge_rule.py.  ASCII output; writes runs/verify_cm_pieces.log; exits 1 on a failure.
Run:  python verify_cm_pieces.py      (under a minute on four processes)
"""
import itertools
import math
import os
import sys
import time

for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "1")
import sympy

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import edge_rule as er  # noqa: E402  (sets below-normal priority on import, through coin_at_five)

os.makedirs(os.path.join(HERE, "runs"), exist_ok=True)
LOG = open(os.path.join(HERE, "runs", "verify_cm_pieces.log"), "w", encoding="utf-8")
FAILS = []
PMAX = 401

# n -> (D, the generators' primes S0, the remaining ramified prime, the twist applied before comparing)
PIECES = {7: (-35, (5,), 7, None), 11: (-1155, (3, 5, 7), 11, None), 15: (-3003, (3, 7, 11), 13, 5)}


def say(s=""):
    print(s, flush=True)
    LOG.write(s + "\n")
    LOG.flush()


def check(name, ok, detail=""):
    say(f"[{'PASS' if ok else 'FAIL'}] {name}" + (f"  ({detail})" if detail else ""))
    if not ok:
        FAILS.append(name)


def vl(j, l):
    v = 0
    while j % l == 0:
        j //= l
        v += 1
    return v


def N_l(n, l):
    """Corollary 2's count (as in verify_conductors.py): the orbits of nodes mod l with critical value of odd valuation"""
    if l == 3:
        return sum(1 for j in range(1, n + 1, 2) if vl(j, 3) >= 2 and vl(j, 3) % 2 == 0)
    return sum(1 for j in range(1, n + 1, 2) if vl(j, l) % 2 == 1)


def conductor(n):
    return math.prod(l ** N_l(n, l) for l in sympy.primerange(3, n + 1))


def disc(n):
    return math.prod(er.signed(l) for l in sympy.primerange(3, n + 1) if N_l(n, l) % 2)


def _traces(p):
    er.low_priority()
    return p, er.airy(p, er.t_values(p, (3, 5, 7, 9, 11, 13, 15)))


def class_number(D):
    """h(D) by counting reduced forms (a, b, c), b^2 - 4ac = D < 0: |b| <= a <= c, b >= 0 if |b| = a or a = c"""
    h = 0
    a = 1
    while 3 * a * a <= -D:
        for b in range(-a + 1, a + 1):
            if (b * b - D) % (4 * a):
                continue
            c = (b * b - D) // (4 * a)
            if c < a or (b < 0 and (a == c)):
                continue
            if math.gcd(math.gcd(a, abs(b)), c) == 1:
                h += 1
        a += 1
    return h


def norm_solutions(D, N):
    """all (u, v) with u >= 0, v >= 0 and u^2 + |D| v^2 = 4 N, u = v mod 2 (gamma = (u + v sqrt D)/2 in O_K)"""
    out = []
    v = 0
    while abs(D) * v * v <= 4 * N:
        r = 4 * N - abs(D) * v * v
        u = math.isqrt(r)
        if u * u == r and (u - v) % 2 == 0:
            out.append((u, v))
        v += 1
    return out


def class_of(D, S0, p):
    """the subset S of S0 with p in the class of a_S, and v from gamma = (u + v sqrt D)/2, (gamma) = p a_S"""
    found = []
    for k in range(len(S0) + 1):
        for S in itertools.combinations(S0, k):
            m = math.prod(S)
            sols = [(u, v) for u, v in norm_solutions(D, p * m) if v != 0 or m == 1]
            # (gamma) has norm p m; for m > 1 it must not be p times a ramified product of norm m alone
            sols = [(u, v) for u, v in sols if not (v == 0 and u * u == 4 * p * m)] if m > 1 else sols
            if sols:
                found.append((S, sols[0]))
    return found


def candidate_ap(D, S0, signs, p):
    """a_p of theta_psi at a split prime p, psi(p_l) = signs[l] * l on the generators"""
    (S, (u, v)), = class_of(D, S0, p)
    m = math.prod(S)
    num = 2 * p * m + D * v * v
    den = m * math.prod(signs[l] for l in S)
    assert num % den == 0, (D, p, S, num, den)
    return num // den


def main():
    t0 = time.time()
    say("verify_cm_pieces.py -- Theorem 9: the pieces at 7, 11 and 15 are CM newforms (Livne's route)")
    say()

    # M0: class groups
    ok0 = True
    for n, (D, S0, last, tw) in PIECES.items():
        r = len(S0)
        h = class_number(D)
        nonprincipal = all(not norm_solutions(D, math.prod(S)) or math.prod(S) == 1
                           for k in range(1, r + 1) for S in itertools.combinations(S0, k))
        split = [p for p in sympy.primerange(3, 3000) if D % p and sympy.jacobi_symbol(D % p, p) == 1]
        one_class = all(len(class_of(D, S0, p)) == 1 for p in split)
        ok0 &= h == 2 ** r and nonprincipal and one_class
        say(f"     D = {D}: h = {h} (2^{r} = {2 ** r}); the products of {S0} are non-principal: {nonprincipal}; each of the "
            f"{len(split)} split primes below 3000 lies in exactly one class a_S: {one_class}")
    check("M0 the class groups are (Z/2)^r, generated by the ramified primes chosen", ok0)

    # M1: the inputs
    ok1 = all(disc(n) == D for n, (D, *_r) in PIECES.items())
    ok1 &= conductor(7) == 35 and conductor(11) == 1155 and conductor(15) == 3 * 25 * 7 * 11 * 13
    ok1 &= N_l(15, 5) == 2
    check("M1 Theorem 8 gives det (D|.), D = -35, -1155, -3003, and Corollary 2 the conductors 35, 1155, 3*5^2*7*11*13; "
          "at 15 the two reflections at 5 make V15 x (5|.) unramified at 5, of conductor 3003", ok1)
    say()

    # the measured traces
    from multiprocessing import Pool
    P = [int(p) for p in sympy.primerange(5, PMAX + 1)]
    with Pool(4) as pool:
        T = dict(pool.map(_traces, P))
    meas = {7: {p: T[p][7] / p ** 3 for p in P}, 11: {p: T[p][11] / p ** 5 for p in P},
            15: {p: er.leg(5, p) * T[p][15] / p ** 7 for p in P if p != 5}}
    say(f"traces from exact counts at the {len(P)} primes 5..{PMAX} ({(time.time() - t0) / 60:.1f} minutes)")

    for n, (D, S0, last, tw) in PIECES.items():
        good = [p for p in meas[n] if D % p and p >= 11]
        matches = []
        for sg in itertools.product((1, -1), repeat=len(S0)):
            signs = dict(zip(S0, sg))
            signs[last] = -math.prod(sg)                 # psi((sqrt D)) = D forces the last sign
            ok = True
            for p in good:
                if sympy.jacobi_symbol(D % p, p) == -1:
                    ok &= meas[n][p] == 0
                else:
                    ok &= meas[n][p] == candidate_ap(D, S0, signs, p)
                if not ok:
                    break
            if ok:
                matches.append(signs)
        say(f"  n = {n}: K = Q(sqrt {D}); candidates matching every good prime 11..{PMAX}: {matches}")
        check(f"M2 n = {n}: exactly one of the {2 ** len(S0)} unramified Hecke characters has the measured traces",
              len(matches) == 1)
        if len(matches) != 1:
            continue
        signs = matches[0]
        edges = {l: meas[n][l] for l in meas[n] if D % l == 0 and l >= 5}
        ok3 = all(edges[l] == signs[l] * l for l in edges)
        detail = ", ".join(f"a_{l} = {edges[l]} counted, {signs[l] * l} from psi" for l in sorted(edges))
        if n in (11, 15):
            detail += f"; a_3 = {signs[3] * 3} from psi, +3 from the functional equation (verify_conductors.py)"
            ok3 &= signs[3] == 1
        check(f"M3 n = {n}: the signs at the ramified primes agree with the edge counts", ok3, detail)
        if n == 7:
            lm = er.LMFDB_35_3_c_b
            mine = {}
            for p in lm:
                if p in (5, 7):
                    mine[p] = signs[p] * p
                elif p == 2:
                    mine[p] = 0 if D % 8 == 5 else None          # 2 is inert in Q(sqrt -35), since -35 = 5 mod 8
                elif sympy.jacobi_symbol(D % p, p) == -1:
                    mine[p] = 0
                else:
                    mine[p] = candidate_ap(D, S0, signs, p)
            check("M4 n = 7: the matching character's theta series is LMFDB 35.3.c.b at every listed prime, a_2 = 0 and "
                  "a_3 = 1 included (Chenevert's theorem, by Livne's route)", all(mine[p] == lm[p] for p in lm),
                  ", ".join(f"a_{p}: {mine[p]} / {lm[p]}" for p in (2, 3, 5, 7, 11, 13, 17)))
    say()
    say(f"time {(time.time() - t0) / 60:.1f} minutes")
    say(f"{'ALL PASS' if not FAILS else 'FAILED: ' + ', '.join(FAILS)}")
    LOG.close()
    sys.exit(1 if FAILS else 0)


if __name__ == "__main__":
    main()
