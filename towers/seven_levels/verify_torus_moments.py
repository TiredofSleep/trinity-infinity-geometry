"""verify_torus_moments.py -- checks each step of TORUS_MOMENTS.md's two proofs: averaged over the non-split torus's
eigenbasis, the fourth-moment ratio of the Wigner values is exactly 2p/(p + 1) (section 3), and their third moment is
exactly 2/(p^2 (p + 1)), with a parity split that depends on p mod 3 (section 6).

Conventions are round 3's: <a|A_(q,k)|b> = [a + b = 2q] w^(k(a - b)), W(u) = <psi|A_u|psi>/p, X|x> = |x + 1>,
Z|x> = w^x |x>, and the symplectic form <u, v> = q_u k_v - k_u q_v.  The torus is generated by the chirp of
oscillator_states.py.  Steps checked:
  1. the chirp U moves phase-point operators by its symplectic map S: U A_u U^dagger = A_(Su)        (p <= 31)
  2. averaging A_u over the torus gives an operator diagonal in U's eigenbasis, with entries p W_j(u)  (p <= 31)
  3. Tr(A_1 A_2 A_3 A_4) = p w^(-2<u1 - u2, u3 - u2>) when u1 - u2 + u3 - u4 = 0, and 0 otherwise       (p <= 31)
  4. the torus's orbits off the origin are p - 1 circles of p + 1 points, and on each the solutions of
     v1 + v3 = v2 + v4 number exactly 3m^2 - 3m (m = p + 1): the three families v2 = v1, v2 = v3, v3 = -v1  (p <= 101)
  5. Phi(C) = sum over v1, v2 in C of w^(4<v1, v2>) adds up, over the p - 1 circles, to (p - 1)(p + 1)    (p <= 101)
  6. Tr(Abar_C^4) = (p/m^4)(2m^2 - 3m + Phi(C)) on every circle                                          (p <= 31)
  7. so the average over the eigenbasis of sum_u W^4 is 1/p^4 + 2(p - 1)/(p^3 (p + 1)^2), and the average
     fourth-moment ratio is 2p/(p + 1)                                                                     (p <= 101)
The third moment (section 6):
  8. Tr(A_1 A_2 A_3) = w^(2<u2 - u1, u3 - u1>), twice the triangle's signed area                          (p <= 31)
  9. the half turn P = A_0 is diagonal in the eigenbasis with entries eps_j = p W_j(0) = +-1; Tr(Abar_C^3) is
     Theta(C)/m^3, the triangle sum; sum_j W_j(u)^3 = Tr(Abar_u^3)/p^3 and sum_j eps_j W_j(u)^3 = Tr(P Abar_u^3)/p^3
                                                                                                          (p <= 31)
 10. in the field F_p(sqrt eps), the Cayley map t -> (t + sqrt eps)/(t - sqrt eps) is a bijection onto the norm-one
     elements other than 1, and G = Im mu1 + Im mu2 - Im(mu1 mu2) = -4 eps (t1 + t2)/((t1^2 - eps)(t2^2 - eps));
     G vanishes exactly on the 3p + 1 degenerate pairs (mu1 = 1, mu2 = 1 or mu1 mu2 = 1)                 (p <= 101)
 11. the triangle sums Theta(C) add up over the p - 1 circles to (p + 1)(p - 1)(2p + 1)                   (p <= 101)
 12. the hexagons: on every circle the pairs v1, v3 with v1 + v3 on the circle number 2(p + 1) when p = 2 mod 3,
     and 0 when p = 1 mod 3                                                                               (p <= 101)
 13. so the average over the eigenbasis of sum_u W^3 is 2/(p^2 (p + 1)), the parity-weighted sum is
     (1 - 2[p = 2 mod 3]/(p + 1))/p^2, and (p + 1)/2 of the states are even                               (p <= 101)
 14. the taper: over all p^2 points the average standardized third moment is -(p + 2)/((p + 1) sqrt(p - 1));
     off the origin the exact formula (offorigin_skew) matches the states (p <= 101) and all 77 of round 12's
     logged non-split averages (torus_moments_run.log, p <= 401)

numpy + oscillator_states.py.  One process, below-normal priority.  ASCII output; writes verify_torus_moments.log
and exits with 1 if a check fails.
Run:  python verify_torus_moments.py     (about twenty seconds)
"""
