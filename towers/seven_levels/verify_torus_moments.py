HERE = os.path.dirname(os.path.abspath(__file__))
LOG = None
OK = True


def say(s=""):
    print(s, flush=True)
    if LOG:
        LOG.write(s + "\n")
        LOG.flush()


def check(label, ok):
    global OK
    OK &= bool(ok)
    say(("PASS  " if ok else "FAIL  ") + label)


def chirp(p):
    """the chirp of oscillator_states.py and the symplectic map it induces on Weyl labels (= phase-point labels)"""
    i4, i2 = pow(4, -1, p), pow(2, -1, p)
    for t in range(p):
        S0 = np.array([[t * i2, 1], [(t * t * i4 - 1) % p, t * i2]], dtype=np.int64) % p
        if osc.mat_order(S0, p, 2 * (p + 1)) == p + 1:
            break
    x = np.arange(p)
    U = np.exp(2j * np.pi * ((t * i4 * (x[:, None] ** 2 + x[None, :] ** 2) - x[:, None] * x[None, :]) % p) / p) / np.sqrt(p)
    X = np.roll(np.eye(p), 1, axis=0)
    Z = np.diag(np.exp(2j * np.pi * x / p))
    lx, lz = osc.weyl_label(U @ X @ U.conj().T, p), osc.weyl_label(U @ Z @ U.conj().T, p)
    return U, np.array([[lx[0], lz[0]], [lx[1], lz[1]]], dtype=np.int64)


def A(q, k, p):
    M = np.zeros((p, p), complex)
    for b in range(p):
        M[(2 * q - b) % p, b] = np.exp(2j * np.pi * (2 * k * (q - b) % p) / p)
    return M


def sym(u, v, p):
    return (u[0] * v[1] - u[1] * v[0]) % p


def orbits(S, p):
    seen, out = set(), []
    for q in range(p):
        for k in range(p):
            if (q, k) == (0, 0) or (q, k) in seen:
                continue
            orb, v = [], np.array([q, k])
            while tuple(v) not in seen:
                seen.add(tuple(v))
                orb.append(tuple(v))
                v = (S @ v) % p
            out.append(orb)
    return out


def field_model(p):
    """the turning wheel as numbers: the norm-one elements (x, y) = x + y sqrt(eps) of F_p(sqrt eps), eps the least
    non-square, and the Cayley map t -> (t + sqrt eps)/(t - sqrt eps) = ((t^2 + eps) + 2t sqrt eps)/(t^2 - eps)"""
    eps = next(e for e in range(2, p) if pow(e, (p - 1) // 2, p) == p - 1)
    T = [(x, y) for x in range(p) for y in range(p) if (x * x - eps * y * y) % p == 1]
    cay = {}
    for t in range(p):
        d = pow((t * t - eps) % p, -1, p)
        cay[t] = ((t * t + eps) * d % p, 2 * t * d % p)
    return eps, T, cay


def offorigin_skew(p):
    """TORUS_MOMENTS.md section 6, exactly: the average over the eigenbasis of the standardized third moment of the
    Wigner values off the origin (round 12's convention), from the two parity classes' average third moments"""
    A3 = Fraction(2, p * (p + 1))                                             # sum over the basis of sum_u W^3
    B3 = Fraction(1, p * p) * (1 - Fraction(2 if p % 3 == 2 else 0, p + 1))  # the same, weighted by parity
    N = p * p - 1
    out = 0.0
    for e in (1, -1):
        n = Fraction(p + e, 2)                                                # (p + 1)/2 even states, (p - 1)/2 odd
        s3 = (A3 + e * B3) / (2 * n) - Fraction(e, p ** 3)                   # the class's mean sum of W^3 off 0
        mu, m2, m3 = (1 - Fraction(e, p)) / N, Fraction(1, p * p * (p + 1)), s3 / N
        out += float(n / p) * float(m3 - 3 * mu * m2 + 2 * mu ** 3) / float(m2 - mu * mu) ** 1.5
    return out


def triangle_phases(P, p):
    """for the points P of a circle: the histogram, over the m^3 ordered triangles, of 2<v2 - v1, v3 - v1> mod p"""
    sy = (P[:, None, 0] * P[None, :, 1] - P[:, None, 1] * P[None, :, 0]) % p          # <vi, vj>
    tri = (sy[:, :, None] + sy[None, :, :] + sy.T[:, None, :]) % p                    # <v1,v2> + <v2,v3> + <v3,v1>
    return np.bincount((2 * tri % p).ravel(), minlength=p)


def main():
    global LOG
    LOG = open(os.path.join(HERE, "verify_torus_moments.log"), "w", encoding="utf-8")
    say("TORUS_MOMENTS.md: averaged over the non-split eigenbasis, mu4/mu2^2 = 2p/(p + 1) (section 3) and the third")
    say("moment is 2/(p^2 (p + 1)), with its parity split (section 6)")
    rng = np.random.default_rng(20261113)
    small = [p for p in osc.PRIMES if p <= 31]
    big = [p for p in osc.PRIMES if p <= 101]
    s1 = s2 = s3 = s6 = s8 = s9 = True
    for p in small:
        U, S = chirp(p)
        V = osc.nonsplit_states(p)[0]                                     # rows: the eigenvectors
        W = osc.wigner(V, p)
        Aall = {(q, k): A(q, k, p) for q in range(p) for k in range(p)}
        Pt = Aall[(0, 0)]                                                 # the half turn
        eps_j = np.rint(p * W[:, 0, 0])
        s9 &= bool(np.allclose(V.conj() @ Pt @ V.T, np.diag(eps_j), atol=1e-9))
        for _ in range(6):                                                # step 1
            u = tuple(rng.integers(0, p, 2))
            Su = tuple((S @ np.array(u)) % p)
            s1 &= bool(np.allclose(U @ Aall[u] @ U.conj().T, Aall[Su], atol=1e-10))
        orbs = orbits(S, p)
        for orb in orbs[:4]:                                              # steps 2 and 6
            Abar = sum(Aall[v] for v in orb) / len(orb)
            D = V.conj() @ Abar @ V.T
            u = orb[0]
            s2 &= bool(np.allclose(D, np.diag(p * W[:, u[0], u[1]]), atol=1e-9))
            m = len(orb)
            Phi = sum(np.exp(2j * np.pi * 4 * sym(a, b, p) / p) for a in orb for b in orb)
            tr4 = np.trace(np.linalg.matrix_power(Abar, 4))
            s6 &= abs(tr4 - p / m ** 4 * (2 * m * m - 3 * m + Phi)) < 1e-9
            A3 = Abar @ Abar @ Abar                                       # step 9
            Theta = (triangle_phases(np.array(orb), p) * np.exp(2j * np.pi * np.arange(p) / p)).sum()
            s9 &= abs(np.trace(A3) - Theta / m ** 3) < 1e-9
            s9 &= abs((W[:, u[0], u[1]] ** 3).sum() - np.trace(A3).real / p ** 3) < 1e-12
            s9 &= abs((eps_j * W[:, u[0], u[1]] ** 3).sum() - np.trace(Pt @ A3).real / p ** 3) < 1e-12
        for _ in range(40):                                               # step 3
            u1, u2, u3 = (tuple(rng.integers(0, p, 2)) for _ in range(3))
            u4 = ((u1[0] - u2[0] + u3[0]) % p, (u1[1] - u2[1] + u3[1]) % p)
            tr = np.trace(Aall[u1] @ Aall[u2] @ Aall[u3] @ Aall[u4])
            d1 = ((u1[0] - u2[0]) % p, (u1[1] - u2[1]) % p)
            d3 = ((u3[0] - u2[0]) % p, (u3[1] - u2[1]) % p)
            s3 &= abs(tr - p * np.exp(2j * np.pi * (-2 * sym(d1, d3, p)) / p)) < 1e-9
            w4 = tuple(rng.integers(0, p, 2))
            if w4 != u4:
                s3 &= abs(np.trace(Aall[u1] @ Aall[u2] @ Aall[u3] @ Aall[w4])) < 1e-9
            e2 = ((u2[0] - u1[0]) % p, (u2[1] - u1[1]) % p)               # step 8
            e3 = ((u3[0] - u1[0]) % p, (u3[1] - u1[1]) % p)
            s8 &= abs(np.trace(Aall[u1] @ Aall[u2] @ Aall[u3]) - np.exp(2j * np.pi * 2 * sym(e2, e3, p) / p)) < 1e-9
    check(f"step 1: the chirp moves phase-point operators by its symplectic map, U A_u U^dagger = A_(Su), at "
          f"{len(small)} primes from 5 to 31", s1)
    check("step 2: averaging A_u over the torus gives an operator diagonal in the eigenbasis, with entries p W_j(u)", s2)
    check("step 3: Tr(A_1 A_2 A_3 A_4) = p w^(-2<u1 - u2, u3 - u2>) when u1 - u2 + u3 - u4 = 0, and 0 otherwise", s3)
    check("step 6: Tr(Abar_C^4) = (p/m^4)(2m^2 - 3m + Phi(C)) on the circles tested", s6)
    s4 = s5 = s7 = s10 = s11 = s12 = s13 = s14 = True
    worst14 = 0.0
    for p in big:
        U, S = chirp(p)
        orbs = orbits(S, p)
        m = p + 1
        s4 &= len(orbs) == p - 1 and all(len(o) == m for o in orbs)
        Phi_sum = 0
        for orb in orbs:
            P = np.array(orb)
            sums = ((P[:, None, :] + P[None, :, :]) % p).reshape(-1, 2)
            counts = np.bincount(sums[:, 0] * p + sums[:, 1], minlength=p * p)
            s4 &= int((counts.astype(np.int64) ** 2).sum()) == 3 * m * m - 3 * m
            symp = (P[:, None, 0] * P[None, :, 1] - P[:, None, 1] * P[None, :, 0]) % p
            Phi_sum += np.exp(2j * np.pi * 4 * symp / p).sum()
        s5 &= abs(Phi_sum - (p - 1) * (p + 1)) < 1e-6
        V = osc.nonsplit_states(p)[0]
        W = osc.wigner(V, p)
        s7 &= abs((W ** 4).sum(axis=(1, 2)).mean() - (1 / p ** 4 + 2 * (p - 1) / (p ** 3 * (p + 1) ** 2))) < 1e-15
        off = W.reshape(len(W), -1)[:, 1:]
        s7 &= abs(((off ** 4).mean(axis=1) / ((off ** 2).mean(axis=1)) ** 2).mean() - 2 * p / (p + 1)) < 1e-12
        # ---- section 6: the third moment
        e, T, cay = field_model(p)                                        # step 10
        m = p + 1
        s10 &= len(T) == m and len(set(cay.values())) == p and set(cay.values()) == set(T) - {(1, 0)}
        Tl = np.array(T, dtype=np.int64)
        x1, y1, x2, y2 = Tl[:, None, 0], Tl[:, None, 1], Tl[None, :, 0], Tl[None, :, 1]
        G = (y1 + y2 - (x1 * y2 + x2 * y1)) % p
        one = (Tl[:, 0] == 1) & (Tl[:, 1] == 0)
        inverse = ((x1 * x2 + e * y1 * y2) % p == 1) & ((x1 * y2 + x2 * y1) % p == 0)
        s10 &= int((G == 0).sum()) == 3 * p + 1 and bool(((G == 0) == (one[:, None] | one[None, :] | inverse)).all())
        for t1 in range(p):
            for t2 in range(p):
                (a1, b1), (a2, b2) = cay[t1], cay[t2]
                want = -4 * e * (t1 + t2) * pow((t1 * t1 - e) * (t2 * t2 - e) % p, -1, p)
                s10 &= (b1 + b2 - (a1 * b2 + a2 * b1) - want) % p == 0
        lab = -np.ones((p, p), dtype=np.int64)                            # steps 11 and 12
        for i, orb in enumerate(orbs):
            for v in orb:
                lab[v] = i
        theta_sum = 0
        for i, orb in enumerate(orbs):
            Po = np.array(orb)
            theta_sum += (triangle_phases(Po, p) * np.exp(2j * np.pi * np.arange(p) / p)).sum()
            sums = (Po[:, None, :] + Po[None, :, :]) % p
            s12 &= int((lab[sums[..., 0], sums[..., 1]] == i).sum()) == (2 * m if p % 3 == 2 else 0)
        s11 &= abs(theta_sum - (p + 1) * (p - 1) * (2 * p + 1)) < 1e-6 * p ** 3
        eps_j = np.rint(p * W[:, 0, 0])                                   # step 13
        cube = (W ** 3).sum(axis=(1, 2))
        s13 &= abs(cube.mean() - 2 / (p * p * (p + 1))) < 1e-15
        s13 &= abs((eps_j * cube).sum() - (1 - (2 / (p + 1) if p % 3 == 2 else 0)) / p ** 2) < 1e-13
        s13 &= bool(np.allclose(np.abs(eps_j), 1)) and int((eps_j == 1).sum()) == (p + 1) // 2
        Wf = W.reshape(len(W), -1)                                        # step 14
        z = (Wf - Wf.mean(axis=1, keepdims=True)) / Wf.std(axis=1, keepdims=True)
        s14 &= abs((z ** 3).mean() + (p + 2) / ((p + 1) * np.sqrt(p - 1))) < 1e-10
        zo = (off - off.mean(axis=1, keepdims=True)) / off.std(axis=1, keepdims=True)
        s14 &= abs((zo ** 3).mean(axis=1).mean() - offorigin_skew(p)) < 1e-10
    logged = {}
    for line in open(os.path.join(HERE, "torus_moments_run.log"), encoding="utf-8"):
        f = line.split()
        if len(f) > 4 and f[0] == "MOM" and f[1].isdigit() and f[2] == "nonsplit":
            logged[int(f[1])] = float(f[4])
    worst14 = max(abs(offorigin_skew(p) - v) for p, v in logged.items())
    s14 &= len(logged) == 77 and worst14 < 6e-7
    check(f"step 4: at the {len(big)} primes from 5 to 101 the torus's orbits off the origin are p - 1 circles of p + 1 "
          f"points, and on each the solutions of v1 + v3 = v2 + v4 number exactly 3m^2 - 3m", s4)
    check("step 5: Phi(C) adds up over the p - 1 circles to (p - 1)(p + 1), at every prime from 5 to 101", s5)
    check("step 7: the average over the eigenbasis of sum_u W^4 is 1/p^4 + 2(p - 1)/(p^3 (p + 1)^2), and the average "
          "fourth-moment ratio is 2p/(p + 1), at every prime from 5 to 101", s7)
    say()
    say("section 6, the third moment:")
    check("step 8: Tr(A_1 A_2 A_3) = w^(2<u2 - u1, u3 - u1>), twice the triangle's signed area, at every prime from 5 "
          "to 31", s8)
    check("step 9: the half turn is diagonal in the eigenbasis with entries eps_j = p W_j(0); Tr(Abar_C^3) is the "
          "triangle sum Theta(C)/m^3; sum_j W_j(u)^3 = Tr(Abar_u^3)/p^3 and sum_j eps_j W_j(u)^3 = Tr(P Abar_u^3)/p^3", s9)
    check("step 10: the Cayley map is a bijection onto the turning wheel less 1, G = -4 eps (t1 + t2)/((t1^2 - eps)"
          "(t2^2 - eps)), and G vanishes exactly on the 3p + 1 degenerate pairs, at every prime from 5 to 101", s10)
    check("step 11: the triangle sums Theta(C) add up over the circles to (p + 1)(p - 1)(2p + 1), at every prime from 5 "
          "to 101", s11)
    check("step 12: on every circle the pairs v1, v3 with v1 + v3 on the circle number 2(p + 1) when p = 2 mod 3 and 0 "
          "when p = 1 mod 3 (the hexagons), at every prime from 5 to 101", s12)
    check("step 13: the average over the eigenbasis of sum_u W^3 is 2/(p^2 (p + 1)), the parity-weighted sum is "
          "(1 - 2[p = 2 mod 3]/(p + 1))/p^2, and (p + 1)/2 states are even, at every prime from 5 to 101", s13)
    check(f"step 14: over all points the average standardized third moment is -(p + 2)/((p + 1) sqrt(p - 1)) (5 to 101); "
          f"off the origin the exact formula matches the states (5 to 101) and all {len(logged)} of round 12's logged "
          f"non-split averages, 5 to 401 (worst difference {worst14:.1e}, the log's rounding)", s14)
    say()
    say("ALL PASS" if OK else "A CHECK FAILED")
    LOG.close()
    sys.exit(0 if OK else 1)


