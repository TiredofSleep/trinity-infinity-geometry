def sym(a, b, p):
    return (a[..., 0] * b[..., 1] - a[..., 1] * b[..., 0]) % p


def phase(U, p):
    """U: integer array (..., k, 2).  Returns (Phi mod p, closure flag) for the product A_U1 ... A_Uk"""
    k = U.shape[-2]
    w = U[..., 0, :].copy()
    Phi = np.zeros(U.shape[:-2], dtype=np.int64)
    i = 1
    while i + 1 < k:
        a, b = (U[..., i, :] - w) % p, (U[..., i + 1, :] - w) % p
        Phi = (Phi + 2 * sym(a, b, p)) % p
        w = (w - U[..., i, :] + U[..., i + 1, :]) % p
        i += 2
    closed = np.ones(U.shape[:-2], bool) if k % 2 else np.all(w % p == U[..., k - 1, :] % p, axis=-1)
    return Phi, closed


def matchings(k):
    """all perfect matchings of 0..k-1, each as a tuple of pairs (i < j), with a non-crossing flag"""
    def rec(rest):
        if not rest:
            yield []
            return
        a = rest[0]
        for j in rest[1:]:
            for m in rec([x for x in rest[1:] if x != j]):
                yield [(a, j)] + m
    out = []
    for m in rec(list(range(k))):
        crossing = any(a < c < b < d or c < a < d < b for (a, b) in m for (c, d) in m if (a, b) != (c, d))
        out.append((tuple(m), not crossing))
    return out


def on_matching(V, M, p):
    """does each configuration in V (..., k, 2) satisfy the matching M (opposite-sign pairs equal, same-sign opposite)?"""
    ok = np.ones(V.shape[:-2], bool)
    for i, j in M:
        if (j - i) % 2:
            ok &= np.all(V[..., i, :] == V[..., j, :], axis=-1)
        else:
            ok &= np.all((V[..., i, :] + V[..., j, :]) % p == 0, axis=-1)
    return ok


def circle(p):
    _, S = vtm.chirp(p)
    orbs = vtm.orbits(S, p)
    C0 = np.array(orbs[0], dtype=np.int64)
    lab = np.zeros((p, p), bool)
    lab[C0[:, 0], C0[:, 1]] = True
    return C0, lab, orbs


def closed_tuples(C0, lab, p, k):
    """the k-tuples on the circle C0 with first vertex C0[0], closed when k is even; returned as an array (n, k, 2)"""
    m = len(C0)
    a0 = C0[0]
    if k % 2:                                                            # odd: every tuple
        idx = np.array(list(itertools.product(range(m), repeat=k - 1)), dtype=np.int64)
        V = np.concatenate([np.broadcast_to(a0, (len(idx), 1, 2)), C0[idx]], axis=1)
        return V
    out = []
    free = k - 2                                                         # v2 .. v_(k-1) free; v_k determined
    for first in range(m):
        rest = np.stack(np.meshgrid(*[np.arange(m)] * (free - 1), indexing="ij"), -1).reshape(-1, free - 1) \
            if free > 1 else np.zeros((1, 0), dtype=np.int64)
        idx = np.concatenate([np.full((len(rest), 1), first), rest], axis=1)
        mid = C0[idx]                                                    # (n, k - 2, 2): v2 .. v_(k-1)
        signs = np.array([(-1) ** i for i in range(1, k - 1)])           # v2 has sign -, v3 +, ...
        last = (a0 + np.einsum("i,nij->nj", signs, mid)) % p             # v_k = v1 - v2 + v3 - ... + v_(k-1)
        keep = lab[last[:, 0], last[:, 1]]
        if keep.any():
            V = np.concatenate([np.broadcast_to(a0, (int(keep.sum()), 1, 2)), mid[keep], last[keep][:, None, :]], axis=1)
            out.append(V)
    return np.concatenate(out) if out else np.zeros((0, k, 2), dtype=np.int64)


def wigner_point_moments(p, kmax):
    """from the states: for each k, sum over the basis of sum over all u of W^k, and of W(0)^k"""
    V = osc.nonsplit_states(p)[0]
    W = osc.wigner(V, p)
    return {k: (float((W ** k).sum()), float((W[:, 0, 0] ** k).sum())) for k in range(2, kmax + 1)}


def calibrate():
    rng = np.random.default_rng(20261114)
    # C1: the phase formula against operator products
    ok1 = True
    for p in (5, 7, 11, 13):
        Aall = {(q, k): vtm.A(q, k, p) for q in range(p) for k in range(p)}
        for k in (3, 4, 5, 6):
            for _ in range(30):
                U = rng.integers(0, p, (k, 2))
                if k % 2 == 0 and rng.random() < 0.6:                   # make most even tuples closed
                    U[k - 1] = (sum(((-1) ** i) * U[i] for i in range(k - 1))) % p
                M = np.eye(p, dtype=complex)
                for u in U:
                    M = M @ Aall[(int(u[0]), int(u[1]))]
                Phi, closed = phase(U[None], p)
                want = (p if k % 2 == 0 else 1) * np.exp(2j * np.pi * Phi[0] / p) * bool(closed[0])
                ok1 &= abs(np.trace(M) - want) < 1e-8
    check("C1", "Tr(A_u1 ... A_uk) = p^[k even] w^Phi [closure], with Phi the fan of triangles, for k = 3 to 6 at "
          "p = 5, 7, 11, 13", ok1)
    # C2: one circle's counts give the sum over circles
    ok2 = True
    for p in (5, 7, 11, 13, 17, 19, 23):
        C0, lab, orbs = circle(p)
        m = p + 1
        mom = wigner_point_moments(p, 6)
        for k in (3, 4, 5, 6):
            if k == 5 and p > 13:
                continue                                                 # m^4 tuples; enough at small p
            V = closed_tuples(C0, lab, p, k)
            Phi, closed = phase(V, p)
            assert closed.all()
            Zp, Np = int((Phi == 0).sum()), len(V)                       # first vertex fixed
            total = (p * (p * m * Zp - m * Np)) if k % 2 == 0 else (p * m * Zp - m ** k)
            Wall, W0 = mom[k]
            from_states = m ** k * p ** k * (Wall - W0) / m              # sum over circles of Tr(S_C^k)
            ok2 &= abs(total - from_states) < 1e-6 * max(1.0, abs(total))
    check("C2", "summed over the circles, Tr(S_C^k) = p(p Z_k - N_k) (even k) or p Z_k - m^k (odd k) from one circle's "
          "counts, as the states' Wigner moments give, for k = 3 to 6 at p = 5 to 23 (k = 5 to 13)", ok2)
    # C3 and C4: pairings
    p = 31
    C0, lab, _ = circle(p)
    ok3, ok4, counts = True, True, {}
    for k in (6, 8):
        Ms = matchings(k)
        counts[k] = (sum(nc for _, nc in Ms), sum(not nc for _, nc in Ms))
        for M, nc in Ms:
            found_nonzero = False
            for _ in range(200):
                V = np.zeros((k, 2), dtype=np.int64)
                V[0] = C0[0]
                for i, j in M:
                    if i != 0:
                        V[i] = C0[rng.integers(len(C0))]
                    V[j] = V[i] if (j - i) % 2 else (-V[i]) % p
                Phi, closed = phase(V[None], p)
                assert closed[0]
                if nc:
                    ok3 &= int(Phi[0]) == 0
                elif int(Phi[0]) != 0:
                    found_nonzero = True
                    break
            if not nc:
                ok4 &= found_nonzero
    check("C3", f"every non-crossing pairing has Phi = 0 ({counts[6][0]} at k = 6, {counts[8][0]} at k = 8; 200 members "
          f"each at p = 31)", ok3 and counts[6][0] == 5 and counts[8][0] == 14)
    check("C4", f"every crossing pairing has a member with Phi != 0 at p = 31 ({counts[6][1]} at k = 6, {counts[8][1]} "
          f"at k = 8)", ok4 and counts[6][1] == 10 and counts[8][1] == 91)
    # C5: k = 4 has no generic closed quadrilaterals
    ok5 = True
    for p in (5, 7, 11, 13, 17, 19, 23, 29, 31):
        C0, lab, _ = circle(p)
        V = closed_tuples(C0, lab, p, 4)
        on_any = np.zeros(len(V), bool)
        for M, _ in matchings(4):
            on_any |= on_matching(V, M, p)
        ok5 &= bool(on_any.all())
    check("C5", "at k = 4 every closed quadrilateral on a circle lies on a pairing, at every prime from 5 to 31", ok5)
    # C6: timings only
    t = time.time()
    C0, lab, _ = circle(11)
    closed_tuples(C0, lab, 11, 6)
    t1 = time.time() - t
    t = time.time()
