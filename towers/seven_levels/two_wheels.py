"""two_wheels.py -- round 8 of PREREG.md, the two-wheels test, committed with its predictions before the run.

The Clifford operations that fix the centre form SL(2, p). Two cyclic wheels run through it, and they share only
the half turn, the coin's edge:
  - the multiplying wheel, k -> ak: p - 1 steps (the wheel of numbers; at 7 the sevenths' six);
  - the turning wheel, the rotations of phase space such as the Fourier transform: p + 1 steps.
Every winner found so far has a symmetry from the turning wheel, or only the half turn.

For each prime p and each order m > 2 that divides p + 1 (turning) or p - 1 (multiplying), the states fixed by the
wheel's subgroup of order m are the eigenvectors of its generator. In each eigenspace the best state is found by
the sign ascent from random states, with the same effort on both wheels; a one-line eigenspace is exact.

numpy only.  Below-normal priority, three threads.  ASCII output; each part writes two_wheels_<part>.log.
Run:  python two_wheels.py A          (the primes 5 to 23)
      python two_wheels.py B          (29)
      python two_wheels.py combine    (after both: scores Y1 to Y3)
Set TWO_WHEELS_SMOKE=1 for a quick test of the code at a tiny size; its scores mean nothing.
"""
import os
import sys

PART = sys.argv[1] if len(sys.argv) > 1 else "A"
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "3")
import time

import numpy as np

import round3 as r3
import round5 as r5

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = 20261112
SMOKE = os.environ.get("TWO_WHEELS_SMOKE") == "1"
PRIMES = {"A": [5, 7, 11, 13, 17, 19, 23], "B": [29]}
WINNER = {5: 0.556677223351, 7: 0.732522000011, 11: 1.032585792267, 13: 1.168522054432, 17: 1.402567380158,
          19: 1.507862142347, 23: 1.700022327901, 29: 1.963715305917}  # the best states found in rounds 2 to 6
TURNING_WINNERS = (5, 7, 17, 19, 29)                                   # where that winner has a turning symmetry
LOG = None
T0 = time.time()


def say(s=""):
    print(s, flush=True)
    if LOG:
        LOG.write(s + "\n")
        LOG.flush()


def starts(k):
    """the search effort in an eigenspace of dimension k, the same rule on both wheels"""
    return 0 if k <= 1 else (max(k * k * 40, 50) if SMOKE else min(3000 * k * k, 300_000))


def mpow(X, e, p):
    Y = (1, 0, 0, 1)
    for _ in range(e):
        Y = r5.mul(Y, X, p)
    return Y


def best_fixed(U, A, p, rng):
    """the best state the cyclic group generated by U fixes: the best over U's eigenspaces"""
    best, best_state, dims = -1.0, None, []
    for Q in r3.eigenspaces(U):
        k = Q.shape[1]
        dims.append(k)
        if k == 1:
            v, s = r3.negativity(r3.wigner(Q[:, 0][None, :], A, p)[0]), Q[:, 0]
        else:
            Ns, reps, _ = r3.search(r3.compress(A, Q), p, starts(k), rng, batch=5000)
            v, s = Ns.max(), Q @ reps[max(reps)][0]
        if v > best:
            best, best_state = v, s
    return best, best_state, sorted(dims, reverse=True)


def run(p, rng):
    A = r3.phase_points(p)
    W = r5.Weil(p, A)
    g = next(a for a in range(2, p) if len({pow(a, e, p) for e in range(1, p)}) == p - 1)
    X = next(Y for Y in W.parent if r5.order(Y, p) == p + 1)            # a generator of the turning wheel
    out = {"turning": {}, "multiplying": {}}
    for m in [m for m in range(3, p + 2) if (p + 1) % m == 0]:
        U = r5.operator(W, mpow(X, (p + 1) // m, p))
        assert r3.perm_order(r3.perm_of(U, A)) == m
        out["turning"][m] = best_fixed(U, A, p, rng)
    for m in [m for m in range(3, p) if (p - 1) % m == 0]:
        a = pow(g, (p - 1) // m, p)
        U = np.eye(p)[[(pow(a, -1, p) * k) % p for k in range(p)]].astype(complex)   # the multiplier k -> ak
        assert r3.perm_order(r3.perm_of(U, A)) == m
        out["multiplying"][m] = best_fixed(U, A, p, rng)
    for wheel in ("turning", "multiplying"):
        for m, (v, s, dims) in sorted(out[wheel].items()):
            say(f"  {p}: {wheel} wheel, order {m}: best {v:.9f} (eigenspace dimensions {dims})")
    T = max(v for v, s, d in out["turning"].values())
    M = max(v for v, s, d in out["multiplying"].values())
    mT = max(out["turning"], key=lambda m: out["turning"][m][0])
    mM = max(out["multiplying"], key=lambda m: out["multiplying"][m][0])
    say(f"turning {p}: {T:.9f} (order {mT}); multiplying {p}: {M:.9f} (order {mM}); winner so far "
        f"{WINNER[p]:.9f} [{time.time() - T0:.0f} s]")
    return T, M


def combine():
    global LOG
    T, M = {}, {}
    for part in ("A", "B"):
        for line in open(os.path.join(HERE, f"two_wheels_{part}.log"), encoding="utf-8"):
            if line.startswith("turning "):
                head, rest = line.split(";", 1)
                p = int(head.split()[1].rstrip(":"))
                T[p] = float(head.split()[2])
                M[p] = float(rest.split(":")[1].split()[0])
    LOG = open(os.path.join(HERE, "two_wheels_combined.log"), "w", encoding="utf-8")
    for p in sorted(T):
        say(f"  {p}: turning {T[p]:.6f}, multiplying {M[p]:.6f}, turning ahead by {T[p] - M[p]:+.6f}; winner so far "
            f"{WINNER[p]:.6f}")
    y1 = all(T[p] > M[p] + 1e-9 for p in T if p >= 11)
    y2 = all(T[p] > WINNER[p] - 1e-6 for p in (17, 19, 29))
    y3 = all(T[p] < WINNER[p] + 1e-6 for p in T)
    say(f"Y1 {'HELD' if y1 else 'DIED'}: at every prime from 11 to 29 the best turning-symmetric state beats the best "
        "multiplying-symmetric one")
    say(f"Y2 {'HELD' if y2 else 'DIED'}: at 17, 19 and 29 the turning search reaches the winner found so far")
    say(f"Y3 {'HELD' if y3 else 'DIED'}: the turning search finds nothing above the winners found so far")
    LOG.close()


def main():
    global LOG
    try:
        import ctypes
        ctypes.windll.kernel32.SetPriorityClass(ctypes.c_void_p(-1), 0x00004000)
    except Exception:
        pass
    if PART == "combine":
        combine()
        return
    LOG = open(os.path.join(HERE, f"two_wheels_{PART}.log"), "w", encoding="utf-8")
    for p in PRIMES[PART]:
        run(p, np.random.default_rng([SEED, p]))
    LOG.close()


if __name__ == "__main__":
    main()
