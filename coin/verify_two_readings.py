# ------------------------------------------------------------------ helpers
def factor(n):
    f, p, m = {}, 2, n
    while p * p <= m:
        while m % p == 0:
            f[p] = f.get(p, 0) + 1
            m //= p
        p += 1
    if m > 1:
        f[m] = f.get(m, 0) + 1
    return f


def squarefree(n):
    return all(e == 1 for e in factor(n).values())


def units(n):
    return [g for g in range(1, n) if gcd(g, n) == 1]


def phi(n):
    return len(units(n)) if n > 1 else 1


def gen_subgroup(gens, m):
    """The subgroup of (Z/m)* generated by gens, as a frozenset of residues mod m."""
    one = 1 % m
    S, todo = {one}, [one]
    while todo:
        y = todo.pop()
        for g in gens:
            z = g * y % m
            if z not in S:
                S.add(z)
                todo.append(z)
    return frozenset(S)


def order(g, m):
    return len(gen_subgroup([g], m))


def prime_powers(n):
    return [p ** j for p, e in factor(n).items() for j in range(1, e + 1)]


def orbit_labels(gens, n):
    """x -> index of the orbit of x under multiplication by the group <gens>."""
    lab = [-1] * n
    k = 0
    for x in range(n):
        if lab[x] < 0:
            lab[x] = k
            todo = [x]
            while todo:
                y = todo.pop()
                for g in gens:
                    z = g * y % n
                    if lab[z] < 0:
                        lab[z] = k
                        todo.append(z)
            k += 1
    return np.array(lab, dtype=np.int64)


def residue_labels(d, n):
    return np.arange(n, dtype=np.int64) % d


def mirror_labels(n):
    x = np.arange(n, dtype=np.int64)
    return np.minimum(x, (-x) % n)


def separates(a, b):
    """Do label maps a and b (arrays over the same points) tell every point apart?"""
    return len(set(zip(a.tolist(), b.tolist()))) == len(a)


def separates_rows(a, B):
    """Vectorised: for label row a and label matrix B, which rows of B separate together with a?"""
    base = int(max(a.max(), B.max())) + 1
    comb = np.sort(a[None, :] * base + B, axis=1)
    return (np.diff(comb, axis=1) != 0).sum(axis=1) + 1 == B.shape[1]


def subgroups(n):
    """All subgroups of (Z/n)* (generated by at most 3 elements -- enough for n <= 40)."""
    U = units(n)
    out = set()
    for r in (1, 2, 3):
        for gens in combinations(U, r):
            out.add(gen_subgroup(gens, n))
    return sorted(out, key=lambda s: (len(s), sorted(s)))


