"""verify_two_readings.py -- checks every [FORCED] line of TWO_READINGS_OF_ZN.md
("When do two readings of Z/n tell every number apart?"), and the archived statements it corrects.

Every 'actual' answer is brute force: do the two label maps give n distinct
label pairs on the n points?  It is compared with the stated criterion.

Standard library + numpy.  ASCII output.  Exit code 1 on any failure.
Run:  python verify_two_readings.py      (well under two minutes)
"""
