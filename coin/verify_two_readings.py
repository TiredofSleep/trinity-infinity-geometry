def resolves(lab, p, n):
    """J34's 'resolves p': numbers that agree mod every other prime of n, but differ, get different labels."""
    others = [q for q in factor(n) if q != p]
    return all(lab[x] != lab[y] for x in range(n) for y in range(n)
               if x != y and all(x % q == y % q for q in others))


