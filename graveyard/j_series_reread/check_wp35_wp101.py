ok_id = ok_dec = ok_end = True
for f in [p for p in range(3, 48) if is_prime(p)]:
    R = []
    for k in range(1, 3 * f + 1):
        s = sum(cmath.exp(2j * math.pi * j / f) for j in range(1, k + 1)) / k
        closed = math.sin(math.pi * k / f) ** 2 / (k * k * math.sin(math.pi / f) ** 2)
        ok_id &= abs(abs(s) ** 2 - closed) < 1e-12
        R.append(closed)
    ok_dec &= all(R[i] > R[i + 1] for i in range(f - 2))
    ok_end &= abs(R[f - 2] - 1 / (f - 1) ** 2) < 1e-12 and abs(R[f - 1]) < 1e-12
check("closed form = squared normalised Dirichlet sum (Fejer-type kernel), primes f < 48, k <= 3f", ok_id)
check("strictly decreasing on k = 1..f-1, R(f-1,f) = 1/(f-1)^2, R(f,f) = 0", ok_dec and ok_end)
f = 100003
ok_lim = all(abs(math.sin(math.pi * u) ** 2 / ((u * f) ** 2 * math.sin(math.pi / f) ** 2)
                 - (math.sin(math.pi * u) / (math.pi * u)) ** 2) < 1e-8 for u in (0.1, 0.25, 0.5, 0.9))
check("R(uf, f) -> sinc^2(u) as f -> infinity (calculus; standard)", ok_lim)
ok_gate = True
for b in range(6, 1000):
    fac = [p for p in range(2, b) if b % p == 0 and is_prime(p)]
    if len(fac) == 2 and fac[0] * fac[1] == b:
        p = fac[0]
        gates = [sum(1 for x in range(1, k + 1) if gcd(x, b) > 1) for k in range(1, p + 1)]
        ok_gate &= gates[:-1] == [0] * (p - 1) and gates[-1] == 1
check("'zero-width gate': for b = pq (p<q), no x < p shares a factor with b, and x = p does (trivial)", ok_gate)

