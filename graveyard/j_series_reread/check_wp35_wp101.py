def check(label, ok):
    print(("  [ok]   " if ok else "  [FAIL] ") + label)
    if not ok:
        FAIL.append(label)


def is_prime(n):
    return n > 1 and all(n % d for d in range(2, int(n ** .5) + 1))


print("=" * 72)
print("WP35 (bundled in J27): R(k,f) = |mean of e^{2 pi i j/f}, j=1..k|^2")
