def cl_table(N):
    a = np.arange(N)[:, None]
    b = np.arange(N)[None, :]
    s = (a + b) % N
    T = np.where(s == (a * b) % N, s, N - 1)
    T = np.where((a == 0) | (b == 0), 0, T)
    T = np.where((a == N - 1) | (b == N - 1), N - 1, T)
    return T


def trees(labels):
    """all unordered binary trees on the given leaf labels (as nested frozensets)"""
    labels = tuple(labels)
    if len(labels) == 1:
        return [labels[0]]
    first, rest = labels[0], labels[1:]
    out = []
    m = len(rest)
    for mask in range(0, 2 ** m):
        left = (first,) + tuple(rest[i] for i in range(m) if mask >> i & 1)
        right = tuple(rest[i] for i in range(m) if not mask >> i & 1)
        if not right:
            continue
        for L in trees(left):
            for R in trees(right):
                out.append((L, R))
    return out


def ev(t, T, X):
    if isinstance(t, int):
        return X[t]
    return T[ev(t[0], T, X), ev(t[1], T, X)]


for N in (7, 10):
    T = cl_table(N)
    for n in (3, 4, 5):
        grids = np.meshgrid(*[np.arange(N)] * n, indexing="ij")
        X = [g.ravel() for g in grids]
        ts = trees(range(n))
        funcs = {ev(t, T, X).tobytes() for t in ts}
        dfact = math.prod(range(2 * n - 3, 0, -2))
        print(f"  N={N}, n={n}: {len(ts)} commutative bracketings, {len(funcs)} distinct functions "
              f"(maximum (2n-3)!! = {dfact})")
        if N == 10:
            check(f"N=10, n={n}: count of bracketings is (2n-3)!!", len(ts) == dfact)
print("  (a finite count cannot show that the operad generated by CL_N is free: that needs every n)")
