def check(label, ok):
    print(("  [ok]   " if ok else "  [FAIL] ") + label)
    if not ok:
        FAIL.append(label)


# ---------------------------------------------------------------- helpers
def factor(n):
    f, p, m = {}, 2, n
    while p * p <= m:
        while m % p == 0:
            f[p] = f.get(p, 0) + 1
            m //= p
        p += 1
    if m > 1:
        f[m] = f.get(m, 0) + 1
    return f


def squarefree(n):
    return all(e == 1 for e in factor(n).values())


def units(n):
    return [g for g in range(1, n) if gcd(g, n) == 1] if n > 1 else [0]


def cyc(g, m):
    """Cyclic subgroup <g mod m> as a frozenset (m >= 1)."""
    if m == 1:
        return frozenset([0])
    s, h = set(), 1 % m
    while h not in s:
        s.add(h)
        h = h * g % m
    return frozenset(s)


def order(g, m):
    return len(cyc(g, m))


def labels_orbits(gens, n):
    """Orbit labels of the subgroup generated by gens acting by multiplication."""
    lab = [-1] * n
    k = 0
    for x in range(n):
        if lab[x] >= 0:
            continue
        stack = [x]
        lab[x] = k
        while stack:
            y = stack.pop()
            for g in gens:
                z = g * y % n
                if lab[z] < 0:
                    lab[z] = k
                    stack.append(z)
        k += 1
    return np.array(lab, dtype=np.int64)


def labels_residue(d, n):
    return np.arange(n, dtype=np.int64) % d


def labels_reflection(n):
    x = np.arange(n, dtype=np.int64)
    return np.minimum(x, (-x) % n)


def separates(l1, l2, n):
    return len(set(zip(l1.tolist(), l2.tolist()))) == n


def separates_many(l1, L, n):
    """For a fixed label row l1 and a matrix L of rows: which rows separate?
    (n = number of points in the rows; labels may be any non-negative ints)"""
    base = int(max(l1.max(), L.max())) + 1
    comb = l1[None, :] * base + L
    comb.sort(axis=1)
    distinct = (np.diff(comb, axis=1) != 0).sum(axis=1) + 1
    return distinct == n


def prime_powers_dividing(n):
    return [p ** j for p, e in factor(n).items() for j in range(1, e + 1)]


