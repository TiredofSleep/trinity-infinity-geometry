"""Independent audit check for J27 / J34 / J35 (partition pairs on Z/n).

Fresh code: every "actual" answer below is computed by brute force from the
partitions themselves (do the two label maps separate all n points?).  It is
then compared with (a) the criterion each paper CLAIMS and (b) the corrected
criterion.  Counts of agreements / counterexamples are printed.

Run:  python -I check_j27_j34_j35.py
"""
